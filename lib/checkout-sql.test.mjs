import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const id = '00000000-0000-0000-0000-000000000001';
const anotherId = '00000000-0000-0000-0000-000000000002';
const hash = 'a'.repeat(64);
const lines = [{ id: '1', size: 'S', quantity: 2 }];

test('PostgreSQL checkout permissions, reservations and payment transitions', async t => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth;
      create table auth.users (id uuid primary key, email_confirmed_at timestamptz);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema public, auth to anon, authenticated, service_role;
      create table public.products (id bigint generated by default as identity primary key, name text,
        slug text, description text, category text, price numeric, stock bigint, sizes text[],
        colours text[], customizable boolean, image_url text, design_images jsonb);
    `);
    for (const filename of ['admin-access.sql', 'product-editing.sql', 'product-creation.sql', 'product-size-stock.sql', 'checkout.sql', 'order-management.sql', 'customer-orders.sql']) {
      await db.exec(readFileSync(new URL(`../supabase/${filename}`, import.meta.url), 'utf8'));
    }
    await db.exec(`insert into public.products(id,name,slug,category,price,stock,sizes,stock_by_size)
      values(1,'Shirt','shirt','tshirts',25,999,array['S','M'],'{"S":3,"M":2}');`);

    const reset = async () => { await db.exec(`delete from public.store_orders; update public.products set stock_by_size='{"S":3,"M":2}' where id=1;`); };
    const start = async (options = {}) => {
      const result = await db.query('select public.store_checkout_start($1,$2,null,$3::jsonb,$4) as result',
        [options.id ?? id, options.hash ?? hash, JSON.stringify(options.lines ?? lines), options.method ?? 'shipping']);
      return result.rows[0].result;
    };
    const stock = async () => (await db.query('select stock,stock_by_size from public.products where id=1')).rows[0];
    const settle = async (state, options = {}) => db.query('select public.store_checkout_settle($1,$2,$3,$4,$5,$6,$7,$8,$9::jsonb)',
      [id, options.session ?? 'cs_test_example', state, 5000, 899, 767, options.total ?? 6666, 'cad',
        JSON.stringify({ shipping: { address: { country: 'CA' } } })]);

    await t.test('public and authenticated users cannot read private orders or call privileged RPCs', async () => {
      for (const role of ['anon','authenticated']) {
        await db.exec(`set role ${role}`);
        try {
          await assert.rejects(db.query('select * from public.store_orders'), /permission denied/);
          await assert.rejects(start(), /permission denied/);
          await assert.rejects(settle('paid'), /permission denied/);
        } finally { await db.exec('reset role'); }
      }
    });
    await t.test('reserves exact sizes, snapshots server prices, and resumes without reserving twice', async () => {
      await reset();
      const order = await start();
      assert.equal(order.subtotal_cents, 5000);
      assert.equal(order.shipping_cents, 899);
      assert.equal(order.items[0].unit_cents, 2500);
      assert.deepEqual((await stock()).stock_by_size, { S: 1, M: 2 });
      await start();
      assert.equal((await start({ id: anotherId })).id, id);
      assert.equal((await stock()).stock, 3);
      await assert.rejects(start({ hash: 'b'.repeat(64) }), /does not match/);
    });
    await t.test('invalid sizes, excess stock and custom input fail atomically', async () => {
      for (const badLines of [[{ id: '1', size: 'L', quantity: 1 }], [{ id: '1', size: 'S', quantity: 4 }],
        [{ id: '1', size: 'S', quantity: 1 }, { id: '999', size: null, quantity: 1 }],
        [{ id: '1', size: 'S', quantity: 1, customization: {} }]]) {
        await reset();
        await assert.rejects(start({ lines: badLines }));
        assert.equal((await stock()).stock, 5);
        assert.equal((await db.query('select count(*)::int as count from public.store_orders')).rows[0].count, 0);
      }
    });
    await t.test('signed settlement requires exact totals/session and paid events are idempotent', async () => {
      await reset(); await start();
      await db.query('select public.store_checkout_bind($1,$2,$3)',[id,hash,'cs_test_example']);
      await assert.rejects(settle('paid', { total: 1 }), /amount mismatch/);
      await assert.rejects(settle('paid', { session: 'cs_test_other' }), /Session mismatch/);
      await settle('paid'); await settle('paid'); await settle('expired');
      assert.equal((await stock()).stock, 3);
      assert.equal((await db.query('select status from public.store_orders')).rows[0].status, 'paid');
    });
    await t.test('confirmed expiration releases once and prevents late fulfillment after release', async () => {
      await reset(); await start();
      await settle('expired'); await settle('expired');
      assert.equal((await stock()).stock, 5);
      assert.deepEqual((await stock()).stock_by_size, { S: 3, M: 2 });
      await assert.rejects(settle('paid'), /manual review/);
    });
    await t.test('pickup fee is zero and legacy shared stock stays shared', async () => {
      await reset();
      // Owner-only fixture change simulates an existing legacy row.
      await db.exec('alter table public.products disable trigger products_validate_size_stock; update public.products set stock_by_size=null,stock=5; alter table public.products enable trigger products_validate_size_stock;');
      assert.equal((await start({ method: 'pickup' })).shipping_cents, 0);
      assert.equal((await stock()).stock, 3);
      assert.equal((await stock()).stock_by_size, null);
      await settle('expired');
      assert.equal((await stock()).stock, 5);
    });
  } finally { await db.close(); }
});
