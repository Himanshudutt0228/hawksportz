import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { checkoutDesign } from './custom-checkout.ts';
import { parseCheckout } from './checkout.ts';
import { consumePurchasedItems } from './cart.ts';
import { refreshCart } from './cart-refresh.ts';

const id = '00000000-0000-0000-0000-000000000001';
const designId = '00000000-0000-0000-0000-000000000002';
const design = { version: 3, id: designId, productId: '1', colour: 'As pictured',
  printTemplate: 'standard', printSizes: { front: 'pocket' }, quantities: { S: 1 }, updatedAt: '2026-10-28',
  layers: [{ id: 'text', kind: 'text', side: 'front', x: 190, y: 200, width: 40, height: 25, rotation: 0, text: 'Test', font: 'Arial', color: '#000000' }] };
const customization = { designId, colour: 'As pictured', sides: ['front'], printSizes: { front: 'pocket' }, printPricePerSide: 0 };
const lines = [{ id: '1', size: 'S', quantity: 1, customization: { designId } }];

test('custom checkout validates product, colour, template, and current design format', () => {
  const product = { id: 1, category: 'tshirts', price: 25, customizable: true };
  assert.ok(checkoutDesign(design, product));
  for (const input of [{ ...design, productId: '2' }, { ...design, colour: 'forged' },
    { ...design, version: 2 }, { ...design, printTemplate: 'headwear' }, { ...design, layers: [] }, { ...design, layers: [{ ...design.layers[0], x: -1000 }] }]) {
    assert.equal(checkoutDesign(input, product), null);
  }
  assert.equal(checkoutDesign(design, { ...product, customizable: false }), null);
  assert.equal(parseCheckout({ requestId: id, method: 'pickup', items: lines }), null);
  assert.ok(parseCheckout({ requestId: id, method: 'pickup', items: lines }, true));
});

test('paid and reserved custom lines retain their design identity', () => {
  const item = { id: '1', slug: 'shirt', name: 'Shirt', size: 'S', quantity: 2, price: 15, stock: 2, customization };
  const other = { ...item, customization: { ...customization, designId: id } };
  assert.deepEqual(consumePurchasedItems([item, other], lines), [{ ...item, quantity: 1 }, other]);
  const pending = [{ id, lines: [{ ...lines[0], name: 'Shirt', slug: 'shirt', unitCents: 1500, customization }] }];
  const result = refreshCart([item], [{ ...item, stock: 1, sizes: ['S'], requiresSize: true }], ['1'], pending);
  assert.equal(result.items[0].quantity, 2);
  assert.equal(result.items[0].customization.designId, designId);
  assert.equal(result.items[0].price, 15);
});

test('custom PostgreSQL checkout keeps designs private and reserves, prices, settles atomically', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key,email_confirmed_at timestamptz);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema public,auth to anon,authenticated,service_role;
      create table public.products(id bigint generated by default as identity primary key,name text,slug text,description text,category text,
        price numeric,stock bigint,sizes text[],colours text[],customizable boolean,image_url text,design_images jsonb);`);
    for (const file of ['admin-access.sql','product-editing.sql','product-creation.sql','product-size-stock.sql','checkout.sql','order-management.sql','custom-checkout.sql']) {
      await db.exec(readFileSync(new URL(`../supabase/${file}`, import.meta.url), 'utf8'));
    }
    // Migration can be rerun without replacing existing designs.
    await db.exec(readFileSync(new URL('../supabase/custom-checkout.sql', import.meta.url), 'utf8'));
    await db.exec(`insert into public.products(id,name,slug,category,price,stock,sizes,stock_by_size,customizable)
      values(1,'Shirt','shirt','tshirts',99,4,array['S'],'{"S":4}',true);`);
    const start = (snapshot = design, cart = lines, requestId = id) => db.query(
      'select public.store_custom_checkout_start($1,$2,null,$3::jsonb,$4,$5::jsonb) as result',
      [requestId,'a'.repeat(64),JSON.stringify(cart),'pickup',JSON.stringify({ [designId]: snapshot })]);
    for (const role of ['anon','authenticated']) {
      await db.exec(`set role ${role}`);
      await assert.rejects(start(), /permission denied/);
      if (role === 'anon') await assert.rejects(db.query('select * from public.store_order_designs'), /permission denied/);
      else assert.equal((await db.query('select * from public.store_order_designs')).rows.length, 0);
      await db.exec('reset role');
    }
    const order = (await start()).rows[0].result;
    assert.equal(order.subtotal_cents, 10150); // Ignores catalogue ready-made price and browser overrides.
    assert.equal(order.items[0].customization.designId, designId);
    assert.equal((await db.query('select stock from products')).rows[0].stock, 3);
    await start();
    assert.equal((await db.query('select stock from products')).rows[0].stock, 3);
    await assert.rejects(start({ ...design, colour: 'changed' }), /Design mismatch/);
    await assert.rejects(db.query('select store_custom_checkout_start($1,$2,null,$3::jsonb,$4,$5::jsonb)',
      [id,'b'.repeat(64),JSON.stringify(lines),'pickup',JSON.stringify({ [designId]: design })]), /does not match/);
    await db.exec(`insert into auth.users values ('${designId}',now()); insert into store_admins(user_id) values ('${designId}');
      select set_config('request.jwt.claim.sub','${designId}',false); set role authenticated;`);
    assert.equal((await db.query('select * from store_order_designs')).rows.length, 1);
    await db.exec(`reset role; delete from store_admins; set role authenticated;`);
    assert.equal((await db.query('select * from store_order_designs')).rows.length, 0);
    await db.exec('reset role');
    assert.deepEqual((await db.query('select designs from store_order_designs')).rows[0].designs[designId], design);
    await db.query("select store_checkout_bind($1,$2,'cs_test_custom')", [id,'a'.repeat(64)]);
    await db.query("select store_checkout_settle($1,'cs_test_custom','expired',null,null,null,null,null,null)", [id]);
    await db.query("select store_checkout_settle($1,'cs_test_custom','expired',null,null,null,null,null,null)", [id]);
    assert.equal((await db.query('select stock from products')).rows[0].stock, 4);
    await assert.rejects(start({ ...design, printSizes: { front: 'free' } }, lines, '00000000-0000-0000-0000-000000000003'), /Invalid print size/);
    assert.equal((await db.query('select stock from products')).rows[0].stock, 4);
    const second = { ...design, id: '00000000-0000-0000-0000-000000000004', printSizes: { front: 'large' } };
    const combined = [...lines, { ...lines[0], customization: { designId: second.id } }, { id: '1', size: 'S', quantity: 1 }];
    const nextId = '00000000-0000-0000-0000-000000000005';
    const mixed = (await db.query('select store_custom_checkout_start($1,$2,null,$3::jsonb,$4,$5::jsonb) as result',
      [nextId,'a'.repeat(64),JSON.stringify(combined),'pickup',JSON.stringify({ [designId]: design, [second.id]: second })])).rows[0].result;
    assert.equal(mixed.items.length, 3);
    assert.equal(mixed.subtotal_cents, 10150 + 10400 + 9900);
    assert.equal((await db.query('select stock from products')).rows[0].stock, 1);
    await db.query("select store_checkout_bind($1,$2,'cs_test_paid_custom')", [nextId,'a'.repeat(64)]);
    for (const state of ['paid','paid','expired']) await db.query(
      "select store_checkout_settle($1,'cs_test_paid_custom',$2,$3,0,0,$3,'cad','{}'::jsonb)", [nextId,state,mixed.subtotal_cents]);
    assert.equal((await db.query('select stock from products')).rows[0].stock, 1);
  } finally { await db.close(); }
});
