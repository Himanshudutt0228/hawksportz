import { test, expect } from "@playwright/test";

test("print area moves with artwork, supports undo and persists per view", async ({ page }, testInfo) => {
  await page.goto("/custom-apparel?resume=1");
  await page.getByLabel("Add your text").fill("AREA TEST");
  await page.getByRole("button", { name: "Add text", exact: true }).click();
  const artwork = page.getByRole("button", { name: "Select AREA TEST", exact: true });
  const original = await artwork.getAttribute("transform");
  await page.getByRole("button", { name: "Move print area", exact: true }).click();
  const mover = page.getByRole("button", { name: "Move Front print area", exact: true });
  await mover.scrollIntoViewIfNeeded();
  const box = await mover.boundingBox();
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2);
  await page.mouse.down();
  await page.mouse.move(box!.x + box!.width / 2 + 40, box!.y + box!.height / 2 + 25, { steps: 6 });
  await page.mouse.up();
  const guide = page.locator('rect[data-print-area="front"]');
  await expect.poll(async () => Number(await guide.getAttribute("x"))).toBeGreaterThan(155);
  const movedX = await guide.getAttribute("x");
  await page.getByRole("button", { name: "Done positioning", exact: true }).click();
  await expect(artwork).not.toHaveAttribute("transform", original!);
  const movedArtwork = await artwork.getAttribute("transform");
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(guide).toHaveAttribute("x", "155");
  await expect(artwork).toHaveAttribute("transform", original!);
  await page.getByRole("button", { name: "Redo", exact: true }).click();
  await expect(guide).toHaveAttribute("x", movedX!);
  await expect(artwork).toHaveAttribute("transform", movedArtwork!);
  await page.getByRole("button", { name: "Left sleeve", exact: true }).click();
  await expect(page.locator('rect[data-print-area="left"]')).toHaveAttribute("x", "370");
  await page.getByRole("button", { name: "Move print area", exact: true }).click();
  const sleeveMover = page.getByRole("button", { name: "Move Left sleeve print area", exact: true });
  await sleeveMover.focus();
  await page.keyboard.press("Shift+ArrowLeft");
  await expect(page.locator('rect[data-print-area="left"]')).toHaveAttribute("x", "360");
  await page.getByRole("button", { name: "Done positioning", exact: true }).click();
  await page.getByRole("button", { name: "Save design", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Design saved on this device");
  await page.reload();
  await expect(page.getByRole("status")).toContainText("Saved design opened");
  await expect(guide).toHaveAttribute("x", movedX!);
  await expect(artwork).toHaveAttribute("transform", movedArtwork!);
  await page.getByRole("button", { name: "Left sleeve", exact: true }).click();
  await expect(page.locator('rect[data-print-area="left"]')).toHaveAttribute("x", "360");
  await page.getByRole("button", { name: "Reset print area", exact: true }).click();
  await expect(page.locator('rect[data-print-area="left"]')).toHaveAttribute("x", "370");
  await page.screenshot({ path: testInfo.outputPath("movable-print-area.png"), fullPage: true });
});

test("empty print-area adjustments can be saved before artwork is added", async ({ page }) => {
  await page.goto("/custom-apparel?resume=1");
  await page.getByRole("button", { name: "Move print area", exact: true }).click();
  await page.getByRole("button", { name: "Move Front print area", exact: true }).focus();
  await page.keyboard.press("Shift+ArrowRight");
  await page.getByRole("button", { name: "Save design", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Design saved on this device");
  await page.reload();
  await expect(page.getByRole("status")).toContainText("Saved design opened");
  await expect(page.locator('rect[data-print-area="front"]')).toHaveAttribute("x", "165");
});
